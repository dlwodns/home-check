// 그림(스캔) 등기부를 OCR로 읽은 글자에서 생기는 흔한 잡음만 걷어 내, 글자 PDF와 같은 모양으로 맞춘다.
// OCR 경로에서만 쓴다. 특정 서류에 맞춘 고침(이름 · 지명 오타 등)은 넣지 않는다.
export function ocrFix(text: string): string {
  return (
    text
      .normalize("NFC")
      // 구역 표시 괄호가 '[' · ']' · '〔'로 읽힌다: "[표제 부 】", "【갑구]" → "【 표제 부 】"
      .replace(/[\[【〔「]\s*(표\s*제\s*부|갑\s*구|을\s*구|공\s*동\s*담\s*보\s*목\s*록)\s*[\]】〕」]/g, "【 $1 】")
      // 구역 이름 글자를 잘못 읽어도("[감구 】") 바로 뒤 정해진 설명으로 구역을 알아본다
      .replace(/^\s*[\[【〔「][^\]】〕」\n]{1,8}[\]】〕」]\s*(?=\(\s*소유권\s*에\s*관한)/gm, "【 갑 구 】 ")
      .replace(/^\s*[\[【〔「][^\]】〕」\n]{1,8}[\]】〕」]\s*(?=\(\s*소유권\s*이외의)/gm, "【 을 구 】 ")
      // 표 세로줄(│)이 'ㅣ' · '｜'로 읽힌다. 홀로 선 모음 'ㅣ'는 등기부 글에 나오지 않으므로 칸 구분으로 본다
      .replace(/[ㅣ｜¦]/g, "|")
      // 줄 앞 표 테두리: "|2 | 소유권이전" → "2 | 소유권이전"
      .replace(/^[\s|]+/gm, "")
      // 순위번호 뒤 잡음: "2 、_ 소유권이전", "3 . 가처분", "1 。" → "2 소유권이전"
      .replace(/^(\s*\d{1,3}(?:-\d{1,2})?)\s*(?:[、。_]|\.(?=\s))[\s、。_.]*/gm, "$1 ")
      // 칸 사이에 끼는 밑줄: "2019년5월20일 _ 2019년…"
      .replace(/(^|\s)_+(?=\s|$)/gm, "$1")
      // 가린 주민등록번호 뒷자리: "910204-\******", "880101-차****", "520306-**재제" → 7자리 모양(별표 2개 이상일 때만)
      .replace(/(\d{6})\s*-\s*(\S{4,8})(?=\s|\||$)/gm, (all, front: string, back: string) =>
        (back.match(/\*/g) ?? []).length >= 2 ? `${front}-${(/^\d/.test(back) ? back[0] : "") + "*".repeat(/^\d/.test(back) ? 6 : 7)}` : all)
      // 금액 안의 숫자 오인식: "금24O,OOO,OOO원" → "금240,000,000원"
      .replace(/금\s*([\dOoIl,]{5,})\s*원/g, (_, n: string) => `금${n.replace(/[Oo]/g, "0").replace(/[Il]/g, "1")}원`)
  );
}

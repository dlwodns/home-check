import { describe, expect, it } from "vitest";
import { ocrFix } from "@/lib/registry/ocrFix";
import { readRegistry } from "@/lib/registry/read";

describe("ocrFix: 그림 등기부 OCR 잡음 정리", () => {
  it("순위번호 뒤 잡음과 표 테두리를 걷어 낸다", () => {
    expect(ocrFix("2 、_ 소유권이전 2019년")).toBe("2 소유권이전 2019년");
    expect(ocrFix("3 . 가처분")).toBe("3 가처분");
    expect(ocrFix("|2 、. ㅣ소유권이전 ㅣ2020년")).toBe("2 |소유권이전 |2020년");
    expect(ocrFix("1-1_ ｜1번근저당권변경")).toBe("1-1 |1번근저당권변경");
  });
  it("구역 표시 괄호를 【 】로 맞춘다(대괄호 [건물] 머리글은 그대로)", () => {
    expect(ocrFix("[표제 부 】 (1동의 건물의 표시 )")).toBe("【 표제 부 】 (1동의 건물의 표시 )");
    expect(ocrFix("【갑구] ( 소유권에 관한 사항 )")).toBe("【 갑 구 】 ( 소유권에 관한 사항 )");
    expect(ocrFix("[집합건물] 경기도")).toBe("[집합건물] 경기도");
    // 구역 이름을 잘못 읽어도 뒤 설명으로
    expect(ocrFix("[감구 】 (소유권에 관한 사항 )")).toBe("【 갑 구 】 (소유권에 관한 사항 )");
    expect(ocrFix("【 올 구] ( 소유권 이외의 권리에 관한 사항 )")).toBe("【 을 구 】 ( 소유권 이외의 권리에 관한 사항 )");
    // 요약표의 "( 갑구 )"는 건드리지 않는다
    expect(ocrFix("1 소유지분현황 ( 갑구 )")).toBe("1 소유지분현황 ( 갑구 )");
  });
  it("날짜 · 금액으로 시작하는 줄은 건드리지 않는다", () => {
    expect(ocrFix("2019년5월20일 매매")).toBe("2019년5월20일 매매");
    expect(ocrFix("1,204.5분의 6.21")).toBe("1,204.5분의 6.21");
  });
  it("깨진 주민번호 가림을 7자리로, 진짜 번호(법인)는 그대로", () => {
    expect(ocrFix("서지훈 910204-\\******")).toBe("서지훈 910204-*******");
    expect(ocrFix("김미경 520306-**재제")).toBe("김미경 520306-*******");
    expect(ocrFix("홍길동 930714-0*****")).toBe("홍길동 930714-0******");
    expect(ocrFix("주식회사누리 165811-0011223")).toBe("주식회사누리 165811-0011223");
  });
  it("금액 안의 O · l을 숫자로", () => {
    expect(ocrFix("채권최고액 금24O,OOO,OOl원")).toBe("채권최고액 금240,000,001원");
  });
  it("정리하면 읽기 규칙이 소유자 · 근저당을 찾는다", () => {
    const ocr = ["【 갑구 】 ( 소유권에 관한 사항 )", "2 、_ 소유권이전 2019년5월20일 2019년4월15일 소유자 김민석 780922-\\******", "【 을 구 】", "1 、 근저당권설정 2019년5월20일 _ 2019년5월20일 채권최고액금240,000,000원", "근저당권자 주식회사가온저축은행 234711-0012345"].join("\n");
    const r = readRegistry(ocrFix(ocr)).read;
    expect(r.current_owner).toBe("김민석");
    expect(r.active_mortgages.map((m) => m.max_claim)).toEqual([240_000_000]);
  });
});

describe("ocrFix: 구역 괄호를 아예 못 읽은 실제 등기부 그림 (11/24 · 11/28 '갑구를 못 찾았어요')", () => {
  it.each([
    ["갑 구 ( 소유권에 관한 사항 )", "【 갑 구 】"],
    ["| 갑구 | (소유권에 관한 사항)", "【 갑 구 】"],
    ["1 감 구 1 ( 소 유 권 에 관 한 사 항 )", "【 갑 구 】"],
    ["( 소유권에 관한 사항 )", "【 갑 구 】"],
    ["을 구 ( 소유권 이외의 권리에 관한 사항 )", "【 을 구 】"],
    ["I 을구 I (소유권 이외의 권리에 관한 사항)", "【 을 구 】"],
  ])("%s → %s", (line, head) => {
    expect(ocrFix(line).trim().startsWith(head)).toBe(true);
  });

  it("요약 쪽의 '소유지분을 제외한 소유권에 관한 사항 ( 갑구 )' 줄은 구역 머리글로 바꾸지 않는다", () => {
    const line = "2. 소유지분을 제외한 소유권에 관한 사항 ( 갑구 )";
    expect(ocrFix(line)).not.toContain("【 갑 구 】");
  });

  it("괄호 없이 읽힌 실제 모양에서도 집주인 · 근저당을 찾는다", () => {
    const text = [
      "표 제 부 ( 건물의 표시 )",
      "1 | 2015년3월10일 | 가상시 한빛구 새내동 101-1 | 철근콘크리트구조 4층 다가구주택 | ",
      "갑 구 ( 소유권에 관한 사항 )",
      "1 | 소유권보존 | 2015년3월10일 제1001호 | | 소유자 이하늘 850101-******* 가상시 한빛구 새내동 101-1",
      "을 구 ( 소유권 이외의 권리에 관한 사항 )",
      "1 | 근저당권설정 | 2015년4월2일 제2002호 | 2015년4월2일 설정계약 | 채권최고액 금240,000,000원 채무자 이하늘 근저당권자 가나은행",
      "-- 이 하 여 백 --",
    ].join("\n");
    const { read, warnings } = readRegistry(ocrFix(text));
    expect(read.current_owner).toBe("이하늘");
    expect(read.active_mortgages).toEqual([{ max_claim: 240000000, creditor: "가나은행" }]);
    expect(warnings.some((w) => w.includes("갑구"))).toBe(false);
  });
});
